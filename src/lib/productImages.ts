export function getProductImagePath(variantId: number) {
  let low = 0;
  let high = PRODUCT_IMAGE_START_IDS.length - 1;
  let selected = PRODUCT_IMAGE_START_IDS[0];

  while (low <= high) {
    const mid = Math.floor((low + high) / 2);
    const startId = PRODUCT_IMAGE_START_IDS[mid];

    if (startId <= variantId) {
      selected = startId;
      low = mid + 1;
    } else {
      high = mid - 1;
    }
  }

  return `/images/products/product-${selected}.jpg`;
}
